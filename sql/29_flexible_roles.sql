-- الدفعة 29: تحويل حقل الدور (role) لحقل مرن
-- بدل ما يكون مقفول على 4 قيم بس (أدمن/شريك/بائع/كاشير)، دلوقتي
-- تقدري تكتبي أي مسمى وظيفي تحبيه (محاسب، مدير مخزن، مسؤول توصيل...).
--
-- سلوك الصلاحيات الافتراضي (مفيش أي تغيير في المنطق ده، هو ده اللي
-- بيحدد الفرق):
--   "أدمن"  → كل الصلاحيات تلقائيًا، من غير ما تحطي حاجة يدوي
--   "شريك"  → أي قسم ماحددتيلوش صلاحية، بيبقى "عرض" تلقائيًا
--   "كاشير" → زي أي دور عادي (مخفي بالكامل افتراضيًا)، بس بيدخل على
--            شاشة الكاشير مباشرة بعد تسجيل الدخول (شكل بس، مش صلاحية)
--   أي اسم تاني (محاسب، بائع، أو أي حاجة تكتبيها) → مخفي بالكامل
--            افتراضيًا، وإنتي اللي بتفتحيله كل قسم يحتاجه بالاسم
-- (قابل لإعادة التشغيل بأمان بالكامل)
-- ============================================================

alter table profiles drop constraint if exists profiles_role_check;
alter table profiles add constraint profiles_role_check check (length(trim(role)) > 0);

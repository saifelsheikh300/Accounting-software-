-- ============================================================
-- الدفعة 28: تثبيت سياسة قراءة الإعدادات (settings) بشكل قاطع
-- ظهرت مشكلة إن حساب الكاشير مبيقدرش يقرا صف الإعدادات خالص (البراند
-- واللوجو والألوان)، بينما الأدمن بيقدر — وده معناه إن فيه سياسة قديمة
-- لسه شغالة في قاعدة البيانات الفعلية مش متطابقة مع الكود في الريبو
-- (احتمال كبير حصل تعارض وقت تنفيذ الملفات يدويًا قبل كده).
-- الملف ده بيمسح أي نسخة قديمة محتملة تحت أي اسم معروف، وبيعيد
-- إنشاء السياسة الصحيحة من الصفر، فمفيش أي فرق يفضل معلق.
-- (قابل لإعادة التشغيل بأمان بالكامل)
-- ============================================================

drop policy if exists "الكل يقرا الإعدادات" on settings;
drop policy if exists "قراءة الإعدادات العامة للكل" on settings;

create policy "قراءة الإعدادات العامة للكل" on settings for select using (
  key not in ('easyOrdersApiKey', 'easyOrdersSecret')
  or fn_has_permission('Settings', 'تعديل')
);

grant execute on all functions in schema public to authenticated;
grant select on settings to authenticated, anon;
